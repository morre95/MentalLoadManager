SELECT
  gen_random_uuid(),
  people.user_id,
  mood_dates.entry_date,
  CASE (EXTRACT(DAY FROM mood_dates.entry_date)::int + people.offset_seed) % 5
    WHEN 0 THEN 'sage'
    WHEN 1 THEN 'sky'
    WHEN 2 THEN 'sand'
    WHEN 3 THEN 'lavender'
    ELSE 'terracotta'
  END AS color_token,
  CASE people.person_key
    WHEN 'eva' THEN
      CASE
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 1 THEN 'Steady'
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 2 THEN 'Busy but fine'
        ELSE 'Optimistic'
      END
    WHEN 'marcus' THEN
      CASE
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 1 THEN 'Focused'
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 2 THEN 'Tired'
        ELSE 'Productive'
      END
    WHEN 'alma' THEN
      CASE
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 1 THEN 'Okay'
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 2 THEN 'A bit stressed'
        ELSE 'Proud'
      END
    ELSE
      CASE
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 1 THEN 'Good'
        WHEN EXTRACT(MONTH FROM mood_dates.entry_date) = 2 THEN 'Energetic'
        ELSE 'Up and down'
